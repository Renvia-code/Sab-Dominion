"""Final-pack checks that the page proof does not cover:
  1. how-made words in every printed PDF (none allowed) and in the PPTX text and notes (the authorship sentence
     only, in the adopted deck's slide 6 notes: O-27 and the orchestrator's correction to C.3);
  2. [you: …] counts in the sheet and the brief (legend mentions listed separately);
  3. talk timings from the S1-S8 speaker notes at 130 words a minute, both decks;
  4. required strings (the model line, the three A4 names, the Q18 rule, the legend labels).

Usage: python -I final_checks.py
"""
import re
import sys
from pathlib import Path

import pymupdf
from pptx import Presentation

sys.stdout.reconfigure(encoding="utf-8")
IP = Path(__file__).resolve().parents[3]
DEL = IP / "deliverables"
PDFS = {
    "deck_adopted": DEL / "01_deck" / "Dominion_reliability_deck_adopted_print_letter.pdf",
    "deck_public": DEL / "01_deck" / "Dominion_reliability_deck_public_print_letter.pdf",
    "sheet": DEL / "02_question_sheet" / "Dominion_question_sheet.pdf",
    "brief": DEL / "03_interview_brief" / "Dominion_interview_brief.pdf",
}
PPTX = {"adopted": DEL / "01_deck" / "Dominion_reliability_deck_adopted.pptx",
        "public": DEL / "01_deck" / "Dominion_reliability_deck_public.pptx"}
if len(sys.argv) > 1 and sys.argv[1] == "v3":       # dry run on the v3 files
    PDFS = {k: p.with_name(p.name.replace("_adopted_print", "_v3_print").replace("_public_print", "_v3_public_print")
                           .replace("sheet.pdf", "sheet_v3.pdf").replace("brief.pdf", "brief_v3.pdf"))
            for k, p in PDFS.items()}
    PPTX = {"adopted": DEL / "01_deck" / "Dominion_reliability_deck_v3.pptx",
            "public": DEL / "01_deck" / "Dominion_reliability_deck_v3_public.pptx"}
HOW = re.compile(r"\b(AI|A\.I\.|assistant|Claude|ChatGPT|LLM|Copilot|agent|agents|subagent|orchestrator|ledger|"
                 r"claims\.csv|interview-prep|MASTER_PROMPT|generated by|auto-generated)\b", re.I)
AUTHORSHIP = "On November 1 it was extended with help, using an AI coding assistant"
WPM = 130


def pdf_text(p):
    return "\n".join(pg.get_text() for pg in pymupdf.open(str(p)))


def flat(t):
    return re.sub(r"\s+", " ", t)


def main():
    bad = 0
    texts = {k: pdf_text(p) for k, p in PDFS.items()}
    print("1. how-made words (the resume's 'AI pilot' at Mercury is the candidate's own work: counted, not flagged)")
    for k, t in texts.items():
        pilots = len(re.findall(r"\bAI\s+pilot", t))
        hits = sorted({m.group(0) for m in HOW.finditer(re.sub(r"\bAI(\s+pilot)", r"XX\1", t))})
        print(f"   {k} PDF: {'clean' if not hits else hits}; 'AI pilot' x{pilots}")
        bad += bool(hits)
    timings = {}
    for v, p in PPTX.items():
        prs = Presentation(str(p))
        per = []
        for i, s in enumerate(prs.slides, 1):
            parts = [sh.text_frame.text for sh in s.shapes if sh.has_text_frame]
            for sh in s.shapes:
                if getattr(sh, "has_table", False) and sh.has_table:
                    parts += [c.text for r in sh.table.rows for c in r.cells]
            slide_txt = " ".join(parts)
            notes = s.notes_slide.notes_text_frame.text if s.has_notes_slide else ""
            for where, txt in (("slide", slide_txt), ("notes", notes)):
                hits = sorted({m.group(0) for m in HOW.finditer(re.sub(r"\bAI(\s+pilot)", r"XX\1", txt))})
                allowed = (v == "adopted" and i == 6 and where == "notes" and AUTHORSHIP in flat(txt)
                           and set(h.lower() for h in hits) <= {"ai", "assistant"})
                if hits and not allowed:
                    print(f"   {v} deck s{i} {where}: {hits}")
                    bad += 1
            if i <= 8:
                per.append(len(notes.split()))
        timings[v] = per
        a6 = prs.slides[5].notes_slide.notes_text_frame.text if prs.slides[5].has_notes_slide else ""
        if v == "adopted":
            print(f"   adopted s6 notes end with the authorship sentence: {AUTHORSHIP in flat(a6)}")
        else:
            print(f"   public s6 notes carry no authorship sentence: {AUTHORSHIP not in flat(a6)}")
    print("2. [you: …] counts (all mentions, including legends)")
    for k in ("sheet", "brief"):
        print(f"   {k}: {flat(texts[k]).count('[you:')}")
    print("3. talk timings, S1-S8 notes at 130 wpm")
    for v, per in timings.items():
        secs = [round(w * 60 / WPM) for w in per]
        tot = sum(secs)
        print(f"   {v}: words {per} = {sum(per)}; {tot // 60}:{tot % 60:02d}")
    print("4. required strings")
    req = {
        "brief": ["30-second opener", "60-second project story", "5-minute route", "The core is a small star",
                  "The November changes were made in the extension, not found by you",
                  "Use the authorship sentence in START_HERE"],
        "sheet": ["The core is a small star"],
        "deck_adopted": ["Original build, Oct 27–31, 2026", "Added Nov 1, 2026"],
    }
    for k, items in req.items():
        for s in items:
            ok = s in flat(texts[k])
            print(f"   {k}: {'ok ' if ok else 'MISSING'} {s!r}")
            bad += not ok
    for k in ("brief", "sheet", "deck_adopted", "deck_public"):
        if re.search(r"star schema", texts[k], re.I):
            print(f"   {k}: still says 'star schema'")
            bad += 1
        for m in re.finditer(r"\b\d+\s+commits?\b|\bbundle\b|\bSHA-?256\b", texts[k], re.I):  # O-40: no counts, no hash
            print(f"   {k}: prints {m.group(0)!r}")
            bad += 1
    for v, p in PPTX.items():                                  # the same in slide text and notes
        prs = Presentation(str(p))
        for i, s in enumerate(prs.slides, 1):
            notes = s.notes_slide.notes_text_frame.text if s.has_notes_slide else ""
            for m in re.finditer(r"\b\d+\s+commits?\b|\bbundle\b|\bSHA-?256\b", notes, re.I):
                print(f"   {v} s{i} notes: {m.group(0)!r}")
                bad += 1
    if "[you: confirm this was your reason]" not in flat(texts["brief"]):
        print("   brief: no '[you: confirm this was your reason]' after the 2019 framing (check whether it is printed)")
    print(f"problems: {bad}")


if __name__ == "__main__":
    main()
